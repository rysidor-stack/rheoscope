"""gen-desk.py -- the desk generator (session D, v3.0-39, desk enrichment).

session-d-design-brief-2026-07-23.md Part 2 item 6: DESK.html is a STATIC PROJECTION, an
actuator-free glass -- zero JavaScript, no <script>/<form>/<button> tags anywhere in the
output, every link either `file://` or a plain relative href. Nothing on the page DOES
anything; it only shows what is already true on disk. Regenerated by the same write-side
sessions that append to the metrics history (the /standing-loop payload and the
scheduled-recipe session -- see .claude/skills/sweep/SKILL.md's amended "Scheduling"
section); a direct, manual /sweep run never calls this script either.

COMPOSED FROM four sources, each read-only and each independently tolerant of absence (an
absent source renders one honest "not available" block in its place, never a crash and
never silently skipped):
  1. SWEEP-BRIEFING.md    -- its three named sections (All clear / Needs your attention /
                              Watching), rendered VERBATIM (escaped, paragraph-wrapped;
                              content is not summarized or reworded).
  2. DECISIONS-PENDING.md -- item TITLES grouped by their source heading, with a "waiting
                              N days" age badge when `receipts/desk/inbox-first-seen.json`
                              exists AND (tolerantly) contains a recognizable entry for
                              that exact item text -- ages are a bonus, never required for
                              the item itself to render (that sidecar is deploy/
                              decision-inbox.py's file, a different builder's; this script
                              only ever reads it, and reads it defensively against shape
                              drift: any JSON that isn't the two shapes this script
                              recognizes degrades to "no ages available", not a crash).
  3. `deploy/check-deadlines.py --json` -- the register's countdowns (attention / fired /
                              watching / if-rows), run fresh at generation time.
  4. `deploy/desk-metrics.py --trends --json` -- the plain-English trend lines over
                              `receipts/desk/metrics-history.jsonl`.

Visual style is cribbed from core/onboarding/SYSTEM-MAP.html's design tokens (the same
:root CSS custom-property palette, light/dark via prefers-color-scheme + a dormant
data-theme override) so the desk reads as part of the same system -- minus SYSTEM-MAP's
tab/toggle/disclosure JS, none of which belongs on an actuator-free page.

Hermetic --self-test: renders from fixtures into a temp dir and asserts both structure
(every section present, absence handled) and the actuator-free invariant itself (zero
<script>/<form>/<button> tags, case-insensitively, anywhere in the output bytes).

Usage:
  gen-desk.py [--root PATH] [--out PATH] [--briefing PATH] [--decisions PATH]
              [--inbox-first-seen PATH] [--deploy-dir PATH] [--history PATH]
              [--register PATH] [--fork-root PATH] [--template-root PATH]
              [--today YYYY-MM-DD]
  gen-desk.py --self-test
Exit: 0 on any completed generation (report/generation primitive, never a gate) |
  nonzero only from --self-test on failure.
"""

