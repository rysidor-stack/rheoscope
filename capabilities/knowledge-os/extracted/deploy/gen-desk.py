# The briefing's three named sections (.claude/skills/sweep/SKILL.md "The briefing") come
# in two shapes: "**All clear:** <content on the same line>" and "**Needs your
# attention:**\n\n1. ..." (heading alone, content follows on later lines). This single
# regex handles both -- the colon is mandatory (distinguishes a real section heading from
# incidental prose starting with one of these words), and group(2) captures whatever
# follows the colon on that same line, empty string when the heading is bare.
SECTION_HEAD_RE = re.compile(
    r"^\s*\**\s*(All clear|Needs your attention|Watching)\s*:\s*\**\s*(.*)$", re.IGNORECASE)
_SECTION_KEY_MAP = {"all clear": "all_clear", "needs your attention": "needs_attention",
                     "watching": "watching"}

MD_H1_RE = re.compile(r"^#\s+(.*)$")
MD_H2_RE = re.compile(r"^##\s+(.*)$")
CHECKBOX_ITEM_RE = re.compile(r"^\s*-\s*\[.\]\s*(.*)$")
DETAILS_TAIL_RE = re.compile(r"\s*\*\(details:.*?\)\*\s*$")
ALL_CLEAR_INBOX_LINE = "Nothing is waiting on you. All clear."


# --------------------------------------------------------------------------- subprocess sensors
# Same interpreter re-use pattern as deploy/desk-metrics.py's _run_json_script -- sys.executable
# is already a working Python, so no PATH-based py/python/python3 search is needed.

def _run_json_script(script_path, extra_args):
    if not os.path.isfile(script_path):
        return None, "%s not found" % os.path.basename(script_path)
    cmd = [sys.executable, script_path, "--json"] + list(extra_args)
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    except Exception as e:  # noqa: BLE001 -- degrade, never crash
        return None, "%s failed to run: %s" % (os.path.basename(script_path), e)
    out = (proc.stdout or "").strip()
    if not out:
        return None, "%s produced no output (exit %s)" % (os.path.basename(script_path), proc.returncode)
    try:
        return json.loads(out), None
    except ValueError:
        return None, "%s output was not valid JSON" % os.path.basename(script_path)


def collect_deadlines_report(deploy_dir, register_path=None, today=None):
    script = os.path.join(deploy_dir, "check-deadlines.py")
    extra = []
    if register_path:
        extra += ["--register", register_path]
    if today:
        extra += ["--today", today]
    data, note = _run_json_script(script, extra)
    if data is None:
        return {"present": False, "note": note}
    if data.get("degraded"):
        return {"present": False, "note": data.get("note", "deadline register absent")}
    return {"present": True, "counts": data.get("counts", {}),
            "rows": data.get("rows", [])}


def collect_trends_report(deploy_dir, history_path):
    script = os.path.join(deploy_dir, "desk-metrics.py")
    extra = ["--trends"]
    if history_path:
        extra += ["--history", history_path]
    data, note = _run_json_script(script, extra)
    if data is None:
        return {"present": False, "note": note}
    return {"present": True, "trends": data.get("trends", []), "note": data.get("note"),
             "load_notes": data.get("load_notes", [])}


# --------------------------------------------------------------------------- SWEEP-BRIEFING.md

def parse_briefing(text):
    """Returns {'all_clear': str|None, 'needs_attention': str|None, 'watching': str|None},
    each the VERBATIM body text of that named section (leading heading line stripped),
    or None if that heading wasn't found at all. A briefing missing every recognized
    heading still returns all-None -- rendered by the caller as its own degrade note,
    never a crash."""
    lines = text.splitlines()
    sections = {"all_clear": None, "needs_attention": None, "watching": None}
    current = None
    buf = []

    def flush():
        if current is not None:
            body = "\n".join(buf).strip("\n")
            sections[current] = body

    for raw in lines:
        m = SECTION_HEAD_RE.match(raw.strip())
        key = _SECTION_KEY_MAP.get(m.group(1).lower()) if m else None
        if key:
            flush()
            current = key
            rest = m.group(2).strip()
            buf = [rest] if rest else []
            continue
        if current is not None:
            buf.append(raw)
    flush()
    return sections


def render_prose(text):
    """Escape-and-paragraph a block of verbatim markdown-ish text: blank-line-separated
    paragraphs, single newlines become <br>. Deliberately minimal -- the design intent is
    VERBATIM content, not a markdown renderer."""
    if not text or not text.strip():
        return "<p class=\"muted\">(empty)</p>"
    paras = re.split(r"\n\s*\n", text.strip())
    out = []
    for p in paras:
        escaped = _html.escape(p).replace("\n", "<br>")
        out.append("<p>%s</p>" % escaped)
    return "\n".join(out)


# --------------------------------------------------------------------------- DECISIONS-PENDING.md

def parse_decisions(text):
    """Returns (all_clear_bool, [{'heading': str, 'items': [str, ...]}, ...]). Item text
    has its trailing '*(details: ...)*' tail stripped (the path already lives in the
    heading grouping / the source file, not needed twice on a static page) and is
    otherwise verbatim."""
    lines = text.splitlines()
    if ALL_CLEAR_INBOX_LINE in text:
        return True, []
    groups = []
    current = None
    for raw in lines:
        m = MD_H2_RE.match(raw.strip())
        if m:
            current = {"heading": m.group(1).strip(), "items": []}
            groups.append(current)
            continue
        m = CHECKBOX_ITEM_RE.match(raw)
        if m and current is not None:
            item_text = DETAILS_TAIL_RE.sub("", m.group(1)).strip()
            current["items"].append(item_text)
    groups = [g for g in groups if g["items"]]
    return False, groups


def load_inbox_first_seen(path):
    """Best-effort reader for deploy/decision-inbox.py's sidecar. Recognizes two
    reasonable shapes and degrades to {} (no ages available) for anything else -- this
    script does not own that sidecar's schema, so it never trusts it further than a
    simple item-text -> date-string lookup permits."""
    if not path or not os.path.isfile(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}
    result = {}
    if isinstance(data, dict):
        for k, v in data.items():
            if isinstance(k, str) and isinstance(v, str):
                result[k] = v
            elif isinstance(k, str) and isinstance(v, dict):
                fs = v.get("first_seen") or v.get("date")
                if isinstance(fs, str):
                    result[k] = fs
    elif isinstance(data, list):
        for entry in data:
            if isinstance(entry, dict):
                item = entry.get("item") or entry.get("key") or entry.get("text")
                fs = entry.get("first_seen") or entry.get("date")
                if isinstance(item, str) and isinstance(fs, str):
                    result[item] = fs
    return result


def age_days(first_seen_str, today):
    try:
        d = datetime.strptime(first_seen_str[:10], "%Y-%m-%d").date()
    except ValueError:
        return None
    return (today - d).days


